// Generates docs/DEPENDENCY-LICENSES.md from package-lock.json and the installed packages' own metadata.
// Usage: node scripts/dependency-licenses.mjs [--check]   (exit 1 in --check mode if the file is stale or a license is not allowed)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const ALLOWED = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|CC0-1\.0|Python-2\.0)$/;

const rows = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (path === "") continue;
  const name = path.replace(/^.*node_modules\//, "");
  const manifest = join(root, path, "package.json");
  const meta = existsSync(manifest) ? JSON.parse(readFileSync(manifest, "utf8")) : {};
  const license = typeof meta.license === "string" ? meta.license : (meta.license?.type ?? info.license ?? "UNKNOWN");
  rows.push({ name, version: info.version, license, scope: info.dev ? "dev" : "runtime", optional: Boolean(info.optional) });
}
rows.sort((a, b) => (a.scope === b.scope ? a.name.localeCompare(b.name) : a.scope === "runtime" ? -1 : 1));

const permissive = (r) => r.license.split(/\s+(?:OR|AND)\s+/).some((l) => ALLOWED.test(l.replace(/[()]/g, "")));
// Reviewed exception: a development-only, unmodified, undistributed MPL-2.0 package (file-level weak copyleft).
const exceptions = rows.filter((r) => r.scope === "dev" && r.license === "MPL-2.0");
const bad = rows.filter((r) => !permissive(r) && !exceptions.includes(r));
const table = (list) =>
  ["| Package | Version | License |", "| --- | --- | --- |", ...list.map((r) => `| ${r.name}${r.optional ? " (optional)" : ""} | ${r.version} | ${r.license} |`)].join("\n");
const runtime = rows.filter((r) => r.scope === "runtime");
const dev = rows.filter((r) => r.scope === "dev");

const text = `# Dependency license audit

Generated by \`node scripts/dependency-licenses.mjs\` from \`package-lock.json\` and each installed package's own
\`package.json\`. Policy: permissive licenses only (MIT, ISC, BSD, Apache-2.0 and similar). ProofGate itself is
${pkg.license} (see \`LICENSE\`; the README's "License decision" note records why: the same license and holder as the
sibling public projects RunProof and ScopeGuard, plus this audit).

Direct runtime dependencies (pinned exactly): ${Object.entries(pkg.dependencies).map(([n, v]) => `${n}@${v}`).join(", ")}.
Direct development dependencies: ${Object.entries(pkg.devDependencies).map(([n, v]) => `${n}@${v}`).join(", ")}.

Result: ${bad.length === 0 ? "**all packages carry an allowed permissive license**" : `**NOT ALLOWED: ${bad.map((b) => `${b.name} (${b.license})`).join(", ")}**`}.
${exceptions.length === 0 ? "" : `Reviewed exception: ${exceptions.length} development-only packages are MPL-2.0 (${[...new Set(exceptions.map((e) => e.name.replace(/-(android|darwin|freebsd|linux|win32)-.*$/, "")))].join(", ")}, pulled in by vitest through vite). MPL-2.0 is file-level weak copyleft; these packages are unmodified, used only to run tests and never shipped or linked into ProofGate, so no MPL obligation attaches to ProofGate itself. No runtime dependency is outside the permissive list.\n`}
Runtime packages: ${runtime.length}. Development-only packages: ${dev.length}. Development-only packages are not shipped
(\`package.json\` \`files\` publishes only \`dist\`, \`schemas\`, \`fixtures\`, selected docs and the license; the packaged-executable
test asserts that no source, test or tooling file is in the tarball).

Non-npm test tooling: the browser smoke uses Playwright (Apache-2.0), which downloads a Chromium build on demand
(\`npx playwright install chromium\`). That browser is used only to run tests on a developer's machine; it is not an npm
dependency, is never vendored, committed or shipped, and is therefore outside this npm audit.

## Runtime (shipped)

${table(runtime)}

## Development only

${table(dev)}
`;
const target = join(root, "docs", "DEPENDENCY-LICENSES.md");
if (process.argv.includes("--check")) {
  const ok = existsSync(target) && readFileSync(target, "utf8") === text && bad.length === 0;
  console.log(ok ? "dependency license audit is current and clean" : "dependency license audit is stale or has disallowed licenses");
  process.exit(ok ? 0 : 1);
}
writeFileSync(target, text);
console.log(`wrote docs/DEPENDENCY-LICENSES.md (${rows.length} packages, ${bad.length} disallowed)`);
process.exit(bad.length === 0 ? 0 : 1);
